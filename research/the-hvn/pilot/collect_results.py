#!/usr/bin/env python3
"""
Copy one scenario's raw artefacts into research/the-hvn/results/<name>/ and write
run-metrics.json and a readable thread.md (posts, comments, interviews).

Usage: collect_results.py <state-file> <ledger-file> <results-folder-name> <scenario label>
"""
import collections
import json
import os
import shutil
import sqlite3
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
state_path, ledger_path, name, label = sys.argv[1:5]
st = json.load(open(os.path.join(HERE, state_path)))
sim = os.path.join(HERE, "..", "..", "..", "backend", "uploads", "simulations", st["simulation_id"])
out = os.path.join(HERE, "..", "results", name)
raw = os.path.join(out, "raw")
os.makedirs(os.path.join(raw, "oasis-logs"), exist_ok=True)

for f in ("simulation_config.json", "reddit_profiles.json", "simulation.log", "run_state.json", "interviews.json",
          "data_fixes_log.txt", "reddit_simulation.db", "simulation_config.json.as-generated.json",
          "reddit_profiles.json.as-generated.json", "simulation_config.json.before-clockshift.json"):
    if os.path.exists(os.path.join(sim, f)):
        shutil.copy(os.path.join(sim, f), os.path.join(raw, f.replace(".json.", ".")))
for f in os.listdir(os.path.join(sim, "log")):
    shutil.copy(os.path.join(sim, "log", f), os.path.join(raw, "oasis-logs", f))
shutil.copy(os.path.join(HERE, ledger_path), os.path.join(raw, "proxy-ledger.jsonl"))
shutil.copy(os.path.join(HERE, state_path), os.path.join(raw, "pilot_state.json"))

# readable export
c = sqlite3.connect(f"file:{os.path.join(raw, 'reddit_simulation.db')}?mode=ro", uri=True)
c.row_factory = sqlite3.Row
db = {t: [dict(r) for r in c.execute(f'select * from "{t}"')]
      for t in ("user", "post", "comment", "like", "comment_like", "dislike", "trace")}
json.dump(db, open(os.path.join(raw, "simulation-db-export.json"), "w"), ensure_ascii=False, indent=1)
cfg = json.load(open(os.path.join(raw, "simulation_config.json")))
names = {a["agent_id"]: a["entity_name"] for a in cfg["agent_configs"]}
u2n = {u["user_id"]: names.get(u["agent_id"], u["name"]) for u in db["user"]}
seed = set(st["activity"]["seed_post_ids"])
iv = json.load(open(os.path.join(raw, "interviews.json"))) if os.path.exists(os.path.join(raw, "interviews.json")) else {}
ivres = ((iv.get("data") or {}).get("result") or {}).get("results") or {}

lines = [f"# {label}: discussion thread and interviews [SIMULATED]", "",
         "Exported verbatim from `raw/reddit_simulation.db` and `raw/interviews.json`. Item IDs (P = post, C = comment) "
         "are the database IDs used for traceability in the analyses. Opening posts P1–P%d were generated by MiroFish's "
         "config step from the briefing and assigned to agents; they are not counted as independent agent activity." % len(seed), ""]
for p in db["post"]:
    tag = " (opening post, generated from briefing)" if p["post_id"] in seed else ""
    lines += [f"## P{p['post_id']} · {u2n.get(p['user_id'])}{tag} · likes {p['num_likes']}", "", p["content"], ""]
    for cm in [x for x in db["comment"] if x["post_id"] == p["post_id"]]:
        lines += [f"- **C{cm['comment_id']} · {u2n.get(cm['user_id'])}** (likes {cm['num_likes']}): {cm['content']}", ""]
lines += ["## Interviews (after the simulation, environment still running)", ""]
for v in ivres.values():
    lines += [f"- **{names.get(v.get('agent_id'))}:** {v.get('response')}", ""]
open(os.path.join(out, "thread.md"), "w").write("\n".join(lines))

L = [json.loads(l) for l in open(os.path.join(raw, "proxy-ledger.jsonl"))]
log = {x["stage"]: x["spent_usd"] for x in st["log"]}
authored = collections.Counter(u2n[p["user_id"]] for p in db["post"] if p["post_id"] not in seed)
authored.update(u2n[x["user_id"]] for x in db["comment"])
spent_before_start = log.get("prepare", 0)
metrics = {
    "scenario": label, "results_folder": f"results/{name}/", "model": sorted({x["model"] for x in L}),
    "graph_memory_updates": False, "mirofish_native_report": "skipped (analysis built from raw logs and interviews)",
    "project_id": st["project_id"], "graph_id": st["graph_id"], "simulation_id": st["simulation_id"],
    "pruned_graph_nodes": st.get("pruned_nodes", []), "agent_entity_types": st.get("chosen_types"),
    "agents": {"count": len(names), "names": list(names.values()), "all_invented": True},
    "clock": f"round 1 behaves as {st.get('clock_shift_hours', 0):02d}:00 (config hour lists shifted)",
    "rounds": {"max": 24, "completed": 24 if st.get("run_status") == "loop_complete" else None},
    "activity": dict(st["activity"], authored_items_per_agent=dict(authored), authors=len(authored),
                     interviews=len(ivres)),
    "requests": {"total": len(L), "free_connectivity_checks": sum(1 for x in L if x["input_tokens"] == 0 and x["output_tokens"] == 0),
                 "http_200": sum(x["status"] == 200 for x in L), "upstream_errors": sum(x["status"] >= 400 for x in L)},
    "tokens": {"input": sum(x["input_tokens"] for x in L), "output": sum(x["output_tokens"] for x in L)},
    "cost_usd": {"total": L[-1]["total_usd"] if L else 0, "cap": 1.0,
                 "by_stage": {"ontology": round(log.get("ontology", 0), 6),
                              "prepare": round(log.get("prepare", 0) - log.get("ontology", 0), 6),
                              "simulation": round(log.get("start", 0) - spent_before_start, 6),
                              "interviews": round(log.get("interview", 0) - log.get("start", 0), 6)},
                 "pricing": "claude-haiku-5-5: USD 0.10 per million input tokens, USD 0.50 per million output tokens"},
}
json.dump(metrics, open(os.path.join(out, "run-metrics.json"), "w"), indent=2, ensure_ascii=False)
print(json.dumps({k: metrics[k] for k in ("activity", "requests", "tokens", "cost_usd")}, indent=1, ensure_ascii=False))
